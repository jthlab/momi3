def print_grad(x, message):
    @jax.custom_vjp
    def pg(x):
        return x

    def pg_fwd(x):
        return x, None

    def pg_bwd(_, x_grad):
        jax.debug.print(message + ": {}", x_grad, ordered=True)
        return (x_grad,)

    pg.defvjp(pg_fwd, pg_bwd)

    return pg(x)


def _rate(t, args):
    # y.shape = (n,) * d
    # y[i1,i2,...,id] = probability of deme 1 have i1 lineages, deme 2 have i2
    # lineages, etc.
    # the rate of coalescence in state (i1, i2, ..., id) is
    # \sum_k \binom{i_k}{2} / 2 / \eta_k(t)
    (etas, _, mats, axes) = args
    eta = jnp.array([1 / 2 / etas[pop](t) for pop in axes])
    # t, eta = print_grad((t, eta), "grad(t)/grad(eta)")
    # t, eta = eqx.internal.debug_backward_nan((t, eta), name="eta", terminate=False)
    return jnp.dot(mats["C"], eta)


def _stats(t, y, args):
    p, s = y
    p /= p.sum()
    c = jnp.sum(p * _rate(t, args))
    return (p, c, s)


def _term(t, y, args):
    # migration matrix at time t
    (etas, M, mats, axes) = args
    M_t = jnp.fill_diagonal(M(t), 0.0, inplace=False)
    # (t, M_t) = eqx.internal.debug_backward_nan((t, M_t), name="t/M_t", terminate=False)
    # transition p forward in time
    p, s = y
    # p = eqx.internal.debug_backward_nan(p, name="p", terminate=False)
    ds = p * _rate(t, args)
    # ds = eqx.internal.debug_backward_nan(ds, name="ds", terminate=False)
    # net rate of transition into state i=(i1,...,id) is
    # \sum_{j\in N(i)} p[j] \sum_{u,v} ju M[u,v] 1{ju == iu + 1, jv == iv - 1}
    # \sum_{j\in N(i)} p[j] \sum_{u,v} B[j,u] M[u,v] X[i,j,u] Y[i,j,v]
    # - N(i) are the neighbors of i (states reachable by one migration event)
    # - The tensors M, X, Y are defined to satisfy the above properties, e.g.
    #   B[j1,...,jd,u] = ju for u=1,...,d
    d = p.ndim
    i = tuple(range(d))
    j = tuple(range(d, 2 * d))
    u = 2 * d + 1
    v = u + 1
    dp_in = jnp.einsum(
        mats["N"],
        i + j,
        p,
        j,
        mats["B"],
        j + (u,),
        M_t,
        (u, v),
        mats["X"],
        i + j + (u,),
        mats["Y"],
        i + j + (v,),
        i,
    )
    # net rate of transition out of state (i1,...,id) due to migration is
    # p[i1,...,id] * \sum_k ik \sum_j M_{k,j}
    dp_out = jnp.einsum(p, i, mats["B"], i + (d + 1,), M_t, (d + 1, d + 2), i)
    dp = dp_in - dp_out
    # should have dp.sum() == 0 at this point, migration is conservative
    # movement into coalescent state
    dp -= ds
    # jax.debug.print("t:{} M_t:{} dp:{} ds:{}".format(t, M_t, dp, ds))
    # (t, M_t, dp, ds) = eqx.internal.debug_backward_nan((t, M_t, dp, ds), name="t/M_t/dp/ds")
    return dp, ds.sum()
