def _outer_sum(T: jax.Array) -> jax.Array:
    """Compute the outer sum of a tensor along its last axis."""
    return reduce(
        lambda a, b: a[..., None] + b[None, :],
        T[1:],
        T[0],
    )


def _mats(d, n):
    B = np.array(list(np.ndindex((n,) * d))).reshape((n,) * d + (d,))
    C = B * (B - 1) / 2
    # construct a tensor D[i1,...,id,j1,...,jd] = 1 if |i-j| = 1, 0 otherwise
    c1 = B[(...,) + (None,) * d + (slice(None),)]
    c2 = B
    # Neighborhood tensor
    N1 = np.abs(c1 - c2).sum(-1) == 2
    N2 = c1.sum(-1) == c2.sum(-1)
    N = N1 & N2
    # X[i,j,u,v] = 1 if iu == jv - 1, 0 otherwise
    X = c1 == c2 - 1
    # Y[i,j,u,v] = 1 if iu == jv + 1, 0 otherwise
    Y = c1 == c2 + 1
    return dict(B=B, C=C, N=N, X=X, Y=Y)


@dataclass(frozen=True, kw_only=True)
class Lift(momi3.sfs.events.Lift):
    def _setup_impl(
        self, child_axes: Axes, ns: PopCounter
    ) -> tuple[Axes, PopCounter, Any]:
        n = list(child_axes.values())[0]
        assert all(v == n for v in child_axes.values())
        # find cliques of migration populations
        G = nx.DiGraph()
        G.add_nodes_from(
            child_axes
        )  # add a node for each population in the child partial likelihood
        G.add_edges_from(self.migrations)
        migration_sets = [tuple(c) for c in nx.connected_components(G.to_undirected())]
        # refine migration sets to only consider who is migrating into who
        migration_sets1 = []
        for cc in migration_sets:
            if len(cc) == 1:
                # if there is no migration, lift the single population in isolation
                migration_sets1.append(cc[0])
                continue
            a = []
            for c1, c2 in it.product(cc, repeat=2):
                if G.has_edge(c1, c2):
                    a.append((c1, c2))
            migration_sets1.append(tuple(a))

        aux = {}
        aux["migration_sets"] = migration_sets1
        aux["axes"] = child_axes
        nsp = deepcopy(ns)
        return child_axes, nsp, aux

    def _execute_impl(self, st: State, params: dict, aux: Any) -> State:
        """Lift partial likelihood.

        Args:
            st: state just before the lifting event
            params: dict of parameters
            aux: dict of auxiliary data generated by setup

        Returns:
            State after the lifting event.
        """
        t0, t1 = [get_path(params, t.path) for t in (self.t0, self.t1)]
        u = jnp.clip(st.t, t0, t1)
        t_isin_t0_t1 = (t0 <= st.t) & (st.t < t1)
        etas = self._etas(params)
        axes = aux["axes"]
        n = st.p.shape[0]
        d = st.p.ndim
        assert st.p.shape == (n,) * d

        if self.migrations == {} or self.terminal:
            # no migrations, so just lift each population to r and t1
            j = jnp.arange(n)
            C = j * (j - 1) // 2
            R = []
            for p in axes:
                R.append(etas[p].R(u) - etas[p].R(t0))
            R = jnp.array(R)
            cum_rates = C[:, None] * R[None, :]
            assert cum_rates.shape == (n, d)
            # convert to (n,) * d outer product tensor
            x = _outer_sum(cum_rates.T)
            assert x.shape == (n,) * d
            # probability of no coalescence
            log_p_nc = -x
            # use double where trick here. taking log(st.p) when st.p has zero entries
            # results in gradient nans!!
